import { triggerBlobDownload, buildExportFilename } from './download.js';

/**
 * Generates and downloads a multi-sheet, fully styled Excel (.xlsx) workbook.
 * Uses dynamic import('exceljs') to prevent bundle bloat.
 */
export async function exportDatasetToXlsx(dataset, options = {}) {
  const { meta, filters = [], summary, rows = [], byCategory = [], byAccount = [] } = dataset;
  const baseCurrency = meta.baseCurrency || 'USD';

  // Dynamic import of exceljs
  const ExcelJS = await import('exceljs');
  const Workbook = ExcelJS.default?.Workbook || ExcelJS.Workbook;

  const workbook = new Workbook();
  workbook.creator = meta.appName || 'Expense Pro';
  workbook.lastModifiedBy = meta.generatedBy || 'User';
  workbook.created = new Date(meta.generatedAt || Date.now());
  workbook.modified = new Date();

  // Colors
  const COLOR_HEADER_BG = 'FF1E293B'; // Slate 800
  const COLOR_HEADER_FG = 'FFFFFFFF'; // White
  const COLOR_ACCENT_BG = 'FF3B82F6'; // Blue
  const COLOR_CARD_BG = 'FFF8FAFC';   // Slate 50
  const COLOR_BORDER = 'FFE2E8F0';    // Slate 200

  // ----------------------------------------------------
  // SHEET 1: EXECUTIVE SUMMARY
  // ----------------------------------------------------
  const summarySheet = workbook.addWorksheet('Summary', {
    views: [{ showGridLines: true }],
  });

  // Title
  summarySheet.mergeCells('A1:E1');
  const titleCell = summarySheet.getCell('A1');
  titleCell.value = `${meta.appName} — Financial Activity Report`;
  titleCell.font = { name: 'Segoe UI', size: 16, bold: true, color: { argb: 'FF0F172A' } };
  summarySheet.getRow(1).height = 30;

  // Metadata block
  summarySheet.getCell('A3').value = 'Workspace:';
  summarySheet.getCell('B3').value = meta.workspaceName;
  summarySheet.getCell('A4').value = 'Period:';
  summarySheet.getCell('B4').value = meta.period;
  summarySheet.getCell('A5').value = 'Generated:';
  summarySheet.getCell('B5').value = new Date(meta.generatedAt).toLocaleString();
  summarySheet.getCell('A6').value = 'Generated By:';
  summarySheet.getCell('B6').value = meta.generatedBy;
  summarySheet.getCell('A7').value = 'Base Currency:';
  summarySheet.getCell('B7').value = baseCurrency;

  ['A3', 'A4', 'A5', 'A6', 'A7'].forEach((cellId) => {
    summarySheet.getCell(cellId).font = { bold: true, color: { argb: 'FF64748B' } };
  });

  // Applied Filters Box
  summarySheet.getCell('D3').value = 'Applied Filters:';
  summarySheet.getCell('D3').font = { bold: true, color: { argb: 'FF64748B' } };

  if (filters.length > 0) {
    filters.forEach((f, idx) => {
      summarySheet.getCell(`D${4 + idx}`).value = `• ${f.label}:`;
      summarySheet.getCell(`E${4 + idx}`).value = f.value;
      summarySheet.getCell(`D${4 + idx}`).font = { bold: true, color: { argb: 'FF334155' } };
    });
  } else {
    summarySheet.getCell('D4').value = 'None (All available data)';
    summarySheet.getCell('D4').font = { italic: true, color: { argb: 'FF94A3B8' } };
  }

  // KPI Metric Cards
  const kpiRowIndex = Math.max(9, 4 + filters.length + 2);

  summarySheet.getCell(`A${kpiRowIndex}`).value = `Total Inflow (${baseCurrency})`;
  summarySheet.getCell(`A${kpiRowIndex + 1}`).value = summary.totalIncome;
  summarySheet.getCell(`A${kpiRowIndex + 1}`).numFmt = `#,##0.00 "${baseCurrency}"`;
  summarySheet.getCell(`A${kpiRowIndex + 1}`).font = { size: 14, bold: true, color: { argb: 'FF16A34A' } }; // Green

  summarySheet.getCell(`B${kpiRowIndex}`).value = `Total Outflow (${baseCurrency})`;
  summarySheet.getCell(`B${kpiRowIndex + 1}`).value = summary.totalExpense;
  summarySheet.getCell(`B${kpiRowIndex + 1}`).numFmt = `#,##0.00 "${baseCurrency}"`;
  summarySheet.getCell(`B${kpiRowIndex + 1}`).font = { size: 14, bold: true, color: { argb: 'FFDC2626' } }; // Red

  summarySheet.getCell(`C${kpiRowIndex}`).value = `Net Cashflow (${baseCurrency})`;
  summarySheet.getCell(`C${kpiRowIndex + 1}`).value = summary.netCashflow;
  summarySheet.getCell(`C${kpiRowIndex + 1}`).numFmt = `#,##0.00 "${baseCurrency}"`;
  summarySheet.getCell(`C${kpiRowIndex + 1}`).font = {
    size: 14,
    bold: true,
    color: { argb: summary.netCashflow >= 0 ? 'FF2563EB' : 'FFDC2626' },
  };

  summarySheet.getCell(`D${kpiRowIndex}`).value = 'Savings Rate';
  summarySheet.getCell(`D${kpiRowIndex + 1}`).value = `${summary.savingsRate}%`;
  summarySheet.getCell(`D${kpiRowIndex + 1}`).font = { size: 14, bold: true, color: { argb: 'FF4F46E5' } };

  summarySheet.getCell(`E${kpiRowIndex}`).value = 'Total Transactions';
  summarySheet.getCell(`E${kpiRowIndex + 1}`).value = summary.transactionCount;
  summarySheet.getCell(`E${kpiRowIndex + 1}`).font = { size: 14, bold: true };

  ['A', 'B', 'C', 'D', 'E'].forEach((col) => {
    summarySheet.getCell(`${col}${kpiRowIndex}`).font = { bold: true, color: { argb: 'FF64748B' } };
  });

  // Category Breakdown on Summary Sheet
  const catTableStart = kpiRowIndex + 4;
  summarySheet.getCell(`A${catTableStart}`).value = 'Category Spending Distribution';
  summarySheet.getCell(`A${catTableStart}`).font = { size: 13, bold: true };

  summarySheet.getRow(catTableStart + 1).values = ['Category', `Amount (${baseCurrency})`, '% of Expenses'];
  summarySheet.getRow(catTableStart + 1).font = { bold: true, color: { argb: COLOR_HEADER_FG } };
  summarySheet.getRow(catTableStart + 1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF334155' },
  };

  byCategory.forEach((cat, idx) => {
    const row = summarySheet.getRow(catTableStart + 2 + idx);
    row.values = [cat.name, cat.total, `${cat.percent}%`];
    row.getCell(2).numFmt = '#,##0.00';
  });

  summarySheet.columns = [
    { width: 26 },
    { width: 24 },
    { width: 24 },
    { width: 22 },
    { width: 26 },
  ];

  // ----------------------------------------------------
  // SHEET 2: DETAILED TRANSACTIONS
  // ----------------------------------------------------
  const txSheet = workbook.addWorksheet('Transactions', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });

  const txHeaders = [
    'Date',
    'Type',
    'Payee / Merchant',
    'Category',
    'Account',
    'Direction',
    `Debit Out (${baseCurrency})`,
    `Credit In (${baseCurrency})`,
    `Net Amount (${baseCurrency})`,
    'Original Amount',
    'Original Currency',
    'Status',
    'Tags',
    'Notes',
  ];

  txSheet.getRow(1).values = txHeaders;
  txSheet.getRow(1).height = 28;
  txSheet.getRow(1).font = { name: 'Segoe UI', size: 11, bold: true, color: { argb: COLOR_HEADER_FG } };
  txSheet.getRow(1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: COLOR_HEADER_BG },
  };
  txSheet.getRow(1).alignment = { vertical: 'middle', horizontal: 'center' };

  // Populate data rows
  rows.forEach((r, idx) => {
    const rowNum = idx + 2;
    const row = txSheet.getRow(rowNum);

    row.values = [
      r.date,
      r.type.toUpperCase(),
      r.payee,
      r.category,
      r.account,
      r.direction.toUpperCase(),
      r.debit > 0 ? r.debit : 0,
      r.credit > 0 ? r.credit : 0,
      r.netAmount,
      r.originalAmount,
      r.originalCurrency,
      r.status,
      r.tags,
      r.notes,
    ];

    // Numeric formatting
    row.getCell(7).numFmt = '#,##0.00;(#,##0.00);"-"';
    row.getCell(8).numFmt = '#,##0.00;(#,##0.00);"-"';
    row.getCell(9).numFmt = '#,##0.00;(#,##0.00);"-"';
    row.getCell(10).numFmt = '#,##0.00';

    // Conditional color for Net
    if (r.netAmount > 0) {
      row.getCell(9).font = { color: { argb: 'FF16A34A' } };
    } else if (r.netAmount < 0) {
      row.getCell(9).font = { color: { argb: 'FFDC2626' } };
    }

    // Light alternating stripe
    if (idx % 2 === 1) {
      row.fill = {
        type: 'pattern',
        pattern: 'solid',
        fgColor: { argb: COLOR_CARD_BG },
      };
    }
  });

  // Bottom Total Row with Excel Subtotal formulas (which respect user filters in Excel!)
  const lastRow = rows.length + 1;
  const totalRowNum = lastRow + 1;
  const totalRow = txSheet.getRow(totalRowNum);

  totalRow.getCell(6).value = 'TOTALS:';
  totalRow.getCell(6).font = { bold: true };
  totalRow.getCell(6).alignment = { horizontal: 'right' };

  totalRow.getCell(7).value = { formula: `SUBTOTAL(9, G2:G${lastRow})` };
  totalRow.getCell(7).numFmt = '#,##0.00';
  totalRow.getCell(7).font = { bold: true };

  totalRow.getCell(8).value = { formula: `SUBTOTAL(9, H2:H${lastRow})` };
  totalRow.getCell(8).numFmt = '#,##0.00';
  totalRow.getCell(8).font = { bold: true };

  totalRow.getCell(9).value = { formula: `SUBTOTAL(9, I2:I${lastRow})` };
  totalRow.getCell(9).numFmt = '#,##0.00';
  totalRow.getCell(9).font = { bold: true };

  totalRow.fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FFF1F5F9' },
  };
  totalRow.border = {
    top: { style: 'thin', color: { argb: 'FFCBD5E1' } },
    bottom: { style: 'double', color: { argb: 'FF475569' } },
  };

  // Turn on AutoFilter
  txSheet.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: lastRow, column: txHeaders.length },
  };

  // Dynamic Column Widths
  txSheet.columns = [
    { width: 14 }, // Date
    { width: 12 }, // Type
    { width: 28 }, // Payee
    { width: 22 }, // Category
    { width: 24 }, // Account
    { width: 12 }, // Direction
    { width: 18 }, // Debit
    { width: 18 }, // Credit
    { width: 18 }, // Net
    { width: 16 }, // Orig Amt
    { width: 12 }, // Orig Curr
    { width: 14 }, // Status
    { width: 22 }, // Tags
    { width: 32 }, // Notes
  ];

  // ----------------------------------------------------
  // SHEET 3: ACCOUNTS BREAKDOWN
  // ----------------------------------------------------
  if (byAccount.length > 0) {
    const accSheet = workbook.addWorksheet('Accounts', {
      views: [{ state: 'frozen', ySplit: 1 }],
    });

    accSheet.getRow(1).values = ['Account', 'Currency', 'Total Inflows', 'Total Outflows', 'Net Change'];
    accSheet.getRow(1).font = { bold: true, color: { argb: COLOR_HEADER_FG } };
    accSheet.getRow(1).fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: COLOR_HEADER_BG },
    };

    byAccount.forEach((acc, idx) => {
      const row = accSheet.getRow(idx + 2);
      row.values = [acc.name, acc.currency, acc.inTotal, acc.outTotal, acc.net];
      row.getCell(3).numFmt = '#,##0.00';
      row.getCell(4).numFmt = '#,##0.00';
      row.getCell(5).numFmt = '#,##0.00';
      if (acc.net > 0) row.getCell(5).font = { color: { argb: 'FF16A34A' } };
      if (acc.net < 0) row.getCell(5).font = { color: { argb: 'FFDC2626' } };
    });

    accSheet.columns = [
      { width: 26 },
      { width: 14 },
      { width: 18 },
      { width: 18 },
      { width: 18 },
    ];
  }

  // Generate buffer and trigger browser download
  const buffer = await workbook.xlsx.writeBuffer();
  const blob = new Blob([buffer], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });

  const filterTags = (filters || []).map((f) => f.value);
  const filename =
    options.filename ||
    buildExportFilename({
      prefix: 'Financial_Report',
      startDate: options.startDate,
      endDate: options.endDate,
      filterTags,
      extension: 'xlsx',
    });

  triggerBlobDownload(blob, filename);
  return filename;
}
