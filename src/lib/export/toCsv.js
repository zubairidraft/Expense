import { escapeCsvField, formatExportNumber } from './formatters.js';
import { triggerBlobDownload, buildExportFilename } from './download.js';

/**
 * Generates an RFC 4180 compliant CSV string with UTF-8 BOM and metadata header block.
 */
export function generateCsvString(dataset) {
  const { meta, filters = [], summary, rows = [] } = dataset;
  const baseCurrency = meta.baseCurrency || 'USD';

  const lines = [];

  // UTF-8 BOM for proper Excel Unicode / Urdu rendering
  const BOM = '\uFEFF';

  // Section 1: Executive Metadata Header
  lines.push(`${escapeCsvField(meta.title || 'Financial Report')}`);
  lines.push(`Workspace,${escapeCsvField(meta.workspaceName)}`);
  lines.push(`Period,${escapeCsvField(meta.period)}`);
  lines.push(`Generated At,${escapeCsvField(new Date(meta.generatedAt).toLocaleString())}`);
  lines.push(`Generated By,${escapeCsvField(meta.generatedBy)}`);

  // Section 2: Applied Filters Summary
  if (filters.length > 0) {
    const filterSummaryStr = filters.map((f) => `${f.label}: ${f.value}`).join(' | ');
    lines.push(`Applied Filters,${escapeCsvField(filterSummaryStr)}`);
  } else {
    lines.push('Applied Filters,None (All data)');
  }

  // Section 3: Summary Totals
  lines.push('');
  lines.push('--- SUMMARY ---');
  lines.push(`Total Inflows (${baseCurrency}),${formatExportNumber(summary.totalIncome)}`);
  lines.push(`Total Outflows (${baseCurrency}),${formatExportNumber(summary.totalExpense)}`);
  lines.push(`Net Cashflow (${baseCurrency}),${formatExportNumber(summary.netCashflow)}`);
  lines.push(`Total Transactions,${summary.transactionCount}`);
  lines.push(`Total Itemized Lines,${summary.lineCount}`);
  lines.push('');

  // Section 4: Data Table
  const headers = [
    'Date',
    'Type',
    'Payee / Description',
    'Category',
    'Account',
    'Direction',
    `Debit Out (${baseCurrency})`,
    `Credit In (${baseCurrency})`,
    `Net Amount (${baseCurrency})`,
    'Original Amount',
    'Original Currency',
    'Status',
    'Tags',
    'Notes',
  ];

  lines.push(headers.map((h) => escapeCsvField(h, false)).join(','));

  for (const r of rows) {
    const rowValues = [
      escapeCsvField(r.date),
      escapeCsvField(r.type.toUpperCase()),
      escapeCsvField(r.payee),
      escapeCsvField(r.category),
      escapeCsvField(r.account),
      escapeCsvField(r.direction.toUpperCase()),
      r.debit > 0 ? formatExportNumber(r.debit) : '0.00',
      r.credit > 0 ? formatExportNumber(r.credit) : '0.00',
      formatExportNumber(r.netAmount),
      formatExportNumber(r.originalAmount),
      escapeCsvField(r.originalCurrency),
      escapeCsvField(r.status),
      escapeCsvField(r.tags),
      escapeCsvField(r.notes),
    ];
    lines.push(rowValues.join(','));
  }

  return BOM + lines.join('\r\n');
}

/**
 * Exports dataset directly to a downloadable CSV file.
 */
export function exportDatasetToCsv(dataset, options = {}) {
  const csvContent = generateCsvString(dataset);
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });

  const filterTags = (dataset.filters || []).map((f) => f.value);
  const filename =
    options.filename ||
    buildExportFilename({
      prefix: 'Financial_Report',
      startDate: options.startDate,
      endDate: options.endDate,
      filterTags,
      extension: 'csv',
    });

  triggerBlobDownload(blob, filename);
  return filename;
}
