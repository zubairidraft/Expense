export const ICON_NAMES = Object.keys(CODEPOINTS);

export default function Icon({ name, size = 20, filled = false, className = '', style, title }) {
  const cp = CODEPOINTS[name];
  if (!cp) return null;
  return (
    <span
      className={`md-icon ${filled ? 'md-icon-filled' : ''} ${className}`}
      style={{ fontSize: size, ...style }}
      aria-hidden={title ? undefined : true}
      title={title}
      role={title ? 'img' : undefined}
    >
      {String.fromCodePoint(cp)}
    </span>
  );
}
